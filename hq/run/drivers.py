from typing import Protocol

from hq.run.stream import StreamEvent


class Driver(Protocol):
    session_id: str | None

    def start(self, prompt: str) -> list[str]: ...
    def on_line(self, line: str) -> tuple[list[StreamEvent], list[str]]: ...
    def follow_up(self, text: str) -> list[str]: ...
    def answer(self, request_id, decision, note) -> list[str]: ...
